import pytest
from unittest.mock import patch
from google.api_core.exceptions import ResourceExhausted, DeadlineExceeded, GoogleAPIError

def test_generate_description_success(client, user_token):
    with patch("app.ai.gemini.genai.GenerativeModel.generate_content") as mock_generate:
        mock_generate.return_value.text = "This is a professional description generated by AI."
        with patch.dict("os.environ", {"GEMINI_API_KEY": "valid_test_api_key"}):
            response = client.post(
                "/api/tasks/generate-description",
                headers={"Authorization": f"Bearer {user_token}"},
                json={"title": "Prepare project presentation"}
            )
            assert response.status_code == 200
            assert response.json()["description"] == "This is a professional description generated by AI."

